// Turn the CP1 palette into the CSS variables the UI reads.
//
// The palette names a role once per scheme and measures it; this script maps those roles onto the names
// shadcn/ui and Tailwind expect, so a component never carries a hex value and the two schemes cannot
// drift apart. Generate the file, never edit it:
//
//   node tools/theme-from-palette.mjs > web/src/styles/tokens.css
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const palette = JSON.parse(readFileSync(join(here, "..", "design", "cp1-palette.json"), "utf8"));

/** shadcn name -> CP1 role. One meaning per token, both schemes use this table. */
const MAP = {
	background: "background",
	foreground: "text",
	card: "elevated",
	"card-foreground": "text",
	popover: "elevated",
	"popover-foreground": "text",
	primary: "accent",
	"primary-foreground": "on_accent",
	secondary: "surface",
	"secondary-foreground": "text",
	muted: "surface",
	"muted-foreground": "muted",
	accent: "press",
	"accent-foreground": "text",
	destructive: "red",
	"destructive-foreground": "on_accent",
	border: "line",
	input: "line",
	ring: "accent",
	success: "green",
	warning: "yellow",
	danger: "red",
	// The volume panel speaks in statuses, not in colours.
	"status-below": "red",
	"status-in": "green",
	"status-above": "yellow",
	"status-high": "orange",
};

/** Radii, in the same shape as the rest of the design: cards hold a panel, controls hold a row. */
const RADIUS = { card: "16px", control: "12px", pill: "999px" };

function block(name) {
	const scheme = palette.palettes[name];
	if (!scheme) throw new Error(`the palette has no scheme named ${name}`);
	const lines = Object.entries(MAP).map(([token, role]) => {
		const value = scheme[role];
		if (!value) throw new Error(`${name}: role ${role} is missing, so ${token} cannot be derived`);
		return `  --${token}: ${value};`;
	});
	for (const [token, value] of Object.entries(RADIUS)) lines.push(`  --radius-${token}: ${value};`);
	// Text on a filled danger button must follow the scheme, not a hard-coded white.
	lines.push(`  --on-solid: ${scheme.on_accent};`);
	return lines.join("\n");
}

const out = `/* Generated by tools/theme-from-palette.mjs from design/cp1-palette.json.
   Edit the palette in iliFalk/CP1-colors, copy it here, and run the script again. */

:root {
  color-scheme: light;
${block("light")}
}

[data-theme="dark"] {
  color-scheme: dark;
${block("dark")}
}

html, body {
  background: var(--background);
  color: var(--foreground);
}
`;

process.stdout.write(out);
